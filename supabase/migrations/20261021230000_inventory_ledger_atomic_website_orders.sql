-- Inventory ledger and atomic website order creation.
-- NULL products.stock_quantity means inventory is not yet configured; never backfill it to zero.
CREATE TABLE IF NOT EXISTS public.inventory_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  movement_type text NOT NULL CHECK (movement_type IN ('opening_balance','receipt','adjustment_increase','adjustment_decrease','order_reserve','order_cancel_release')),
  quantity_delta numeric NOT NULL CHECK (quantity_delta <> 0),
  stock_before numeric,
  stock_after numeric,
  order_id uuid REFERENCES public.orders(id) ON DELETE RESTRICT,
  reason text NOT NULL DEFAULT '',
  created_by text NOT NULL DEFAULT 'system',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS inventory_movements_product_created_idx ON public.inventory_movements(product_id,created_at DESC);
CREATE INDEX IF NOT EXISTS inventory_movements_order_idx ON public.inventory_movements(order_id) WHERE order_id IS NOT NULL;
ALTER TABLE public.inventory_movements ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins can read inventory movements" ON public.inventory_movements;
CREATE POLICY "Admins can read inventory movements" ON public.inventory_movements FOR SELECT TO authenticated
USING (lower(coalesce(auth.jwt()->>'email','')) IN ('halalfoodbd.official@gmail.com'));
REVOKE ALL ON public.inventory_movements FROM anon,authenticated;
GRANT SELECT ON public.inventory_movements TO authenticated;
GRANT ALL ON public.inventory_movements TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.inventory_movements_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.log_manual_product_stock_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_delta numeric; v_type text;
BEGIN
 IF current_setting('app.inventory_system_update',true)='on' OR NEW.stock_quantity IS NOT DISTINCT FROM OLD.stock_quantity THEN RETURN NEW; END IF;
 IF NEW.stock_quantity IS NULL THEN RETURN NEW; END IF;
 IF OLD.stock_quantity IS NULL THEN v_delta:=NEW.stock_quantity; v_type:='opening_balance';
 ELSE v_delta:=NEW.stock_quantity-OLD.stock_quantity; v_type:=CASE WHEN v_delta>0 THEN 'receipt' ELSE 'adjustment_decrease' END; END IF;
 IF v_delta<>0 THEN
  INSERT INTO public.inventory_movements(product_id,movement_type,quantity_delta,stock_before,stock_after,reason,created_by)
  VALUES(NEW.id,v_type,v_delta,OLD.stock_quantity,NEW.stock_quantity,
   CASE WHEN OLD.stock_quantity IS NULL THEN 'Initial stock configured in admin product editor' ELSE 'Manual stock adjustment in admin product editor' END,
   lower(coalesce(auth.jwt()->>'email','admin-panel')));
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_log_manual_product_stock_change ON public.products;
CREATE TRIGGER trg_log_manual_product_stock_change AFTER UPDATE OF stock_quantity ON public.products
FOR EACH ROW EXECUTE FUNCTION public.log_manual_product_stock_change();

CREATE OR REPLACE FUNCTION public.create_website_order(p_order jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE
 v_name text:=left(trim(coalesce(p_order->>'name','')),80);
 v_phone text:=regexp_replace(coalesce(p_order->>'phone',p_order->>'mobile',''),'[[:space:]-]','','g');
 v_email text:=nullif(left(trim(coalesce(p_order->>'email','')),120),'');
 v_address text:=left(trim(coalesce(p_order->>'address','')),300);
 v_notes text:=left(trim(coalesce(p_order->>'notes','')),500);
 v_zone text:=coalesce(p_order->>'deliveryZone',p_order->>'delivery_zone','');
 v_payment text:=lower(coalesce(p_order->>'paymentMethod',p_order->>'payment_method','cash_on_delivery'));
 v_delivery numeric; v_order_number text:=nullif(left(trim(coalesce(p_order->>'orderId','')),20),'');
 v_customer_id uuid; v_order_id uuid; v_subtotal numeric:=0; v_total numeric:=0;
 v_line jsonb; v_product public.products%ROWTYPE; v_qty numeric; v_before numeric; v_after numeric;
 v_item_rows jsonb:=coalesce(p_order->'items','[]'::jsonb); v_existing public.orders%ROWTYPE;
BEGIN
 IF length(v_name)<2 THEN RAISE EXCEPTION 'Please enter your full name.' USING ERRCODE='22023'; END IF;
 IF v_phone !~ '^01[0-9]{9}$' THEN RAISE EXCEPTION 'Please enter a valid 11-digit mobile number (01XXXXXXXXX).' USING ERRCODE='22023'; END IF;
 IF v_email IS NOT NULL AND v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN RAISE EXCEPTION 'Please enter a valid email address.' USING ERRCODE='22023'; END IF;
 IF length(v_address)<5 THEN RAISE EXCEPTION 'Please enter your full address.' USING ERRCODE='22023'; END IF;
 IF v_zone NOT IN ('inside_dhaka','outside_dhaka') THEN RAISE EXCEPTION 'Please select a valid delivery area.' USING ERRCODE='22023'; END IF;
 IF v_payment<>'cash_on_delivery' THEN RAISE EXCEPTION 'Cash on Delivery is the only available payment method.' USING ERRCODE='22023'; END IF;
 v_delivery:=CASE WHEN v_zone='inside_dhaka' THEN 70 ELSE 120 END;
 IF v_order_number IS NOT NULL AND v_order_number !~ '^HF-[0-9]{4,6}$' THEN v_order_number:=NULL; END IF;
 IF jsonb_typeof(v_item_rows)<>'array' OR jsonb_array_length(v_item_rows)=0 OR jsonb_array_length(v_item_rows)>30 THEN
  RAISE EXCEPTION 'Please add between 1 and 30 order items.' USING ERRCODE='22023'; END IF;
 IF v_order_number IS NOT NULL THEN
  PERFORM pg_advisory_xact_lock(hashtext(v_order_number));
  SELECT * INTO v_existing FROM public.orders WHERE order_number=v_order_number LIMIT 1;
  IF FOUND THEN RETURN jsonb_build_object('success',true,'duplicate',true,'orderId',v_existing.order_number,'subtotal',v_existing.subtotal,'deliveryCharge',v_existing.delivery_charge,'total',v_existing.total,'orderTotal',v_existing.total); END IF;
 END IF;
 IF (SELECT count(*) FROM public.orders WHERE customer_phone=v_phone AND ordered_at>=now()-interval '10 minutes')>=5 THEN
  RAISE EXCEPTION 'Too many orders from this number in a short time. Please contact us by phone.' USING ERRCODE='P0001'; END IF;
 SELECT id INTO v_customer_id FROM public.customers WHERE phone=v_phone ORDER BY created_at LIMIT 1;
 IF v_customer_id IS NULL THEN INSERT INTO public.customers(name,phone,email,address) VALUES(v_name,v_phone,v_email,v_address) RETURNING id INTO v_customer_id; END IF;
 FOR v_line IN SELECT value FROM jsonb_array_elements(v_item_rows) LOOP
  SELECT * INTO v_product FROM public.products WHERE is_active=true AND
   (lower(name)=lower(left(trim(coalesce(v_line->>'product',v_line->>'name',v_line->>'slug','')),120))
    OR lower(slug)=lower(left(trim(coalesce(v_line->>'product',v_line->>'name',v_line->>'slug','')),120))) LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'Sorry, this product is not available: %',left(trim(coalesce(v_line->>'product',v_line->>'name',v_line->>'slug','')),120) USING ERRCODE='22023'; END IF;
  BEGIN v_qty:=floor(coalesce(nullif(v_line->>'quantity','')::numeric,nullif(v_line->>'qty','')::numeric,1));
  EXCEPTION WHEN others THEN RAISE EXCEPTION 'Please enter a valid quantity.' USING ERRCODE='22023'; END;
  IF v_qty<1 OR v_qty>99 THEN RAISE EXCEPTION 'Please enter a valid quantity.' USING ERRCODE='22023'; END IF;
  v_subtotal:=v_subtotal+v_product.price*v_qty;
 END LOOP;
 INSERT INTO public.orders(order_number,customer_id,customer_name,customer_phone,customer_email,delivery_address,subtotal,delivery_charge,total,delivery_zone,payment_method,currency,status,source,notes,ordered_at)
 VALUES(v_order_number,v_customer_id,v_name,v_phone,v_email,v_address,v_subtotal,v_delivery,v_subtotal+v_delivery,v_zone,'cash_on_delivery','BDT','pending','website_parallel',v_notes,now())
 RETURNING id INTO v_order_id;
 PERFORM set_config('app.inventory_system_update','on',true);
 FOR v_line IN SELECT value FROM jsonb_array_elements(v_item_rows) LOOP
  SELECT * INTO v_product FROM public.products WHERE is_active=true AND
   (lower(name)=lower(left(trim(coalesce(v_line->>'product',v_line->>'name',v_line->>'slug','')),120))
    OR lower(slug)=lower(left(trim(coalesce(v_line->>'product',v_line->>'name',v_line->>'slug','')),120))) LIMIT 1 FOR UPDATE;
  v_qty:=floor(coalesce(nullif(v_line->>'quantity','')::numeric,nullif(v_line->>'qty','')::numeric,1));
  IF v_product.stock_quantity IS NOT NULL THEN
   v_before:=v_product.stock_quantity;
   IF v_before<v_qty THEN RAISE EXCEPTION 'Not enough stock for %.',v_product.name USING ERRCODE='22023'; END IF;
   v_after:=v_before-v_qty;
   UPDATE public.products SET stock_quantity=v_after,updated_at=now() WHERE id=v_product.id;
   INSERT INTO public.inventory_movements(product_id,movement_type,quantity_delta,stock_before,stock_after,order_id,reason,created_by)
   VALUES(v_product.id,'order_reserve',-v_qty,v_before,v_after,v_order_id,'Stock reserved for website order '||coalesce(v_order_number,v_order_id::text),'order-sync');
  END IF;
  INSERT INTO public.order_items(order_id,product_id,product_name,quantity,unit,unit_price,line_total,product_image_url)
  VALUES(v_order_id,v_product.id,v_product.name,v_qty,v_product.unit_type,v_product.price,v_product.price*v_qty,
   CASE WHEN coalesce(v_line->>'image',v_line->>'imageUrl','') ~ '^images/[A-Za-z0-9_./-]+$' THEN coalesce(v_line->>'image',v_line->>'imageUrl') ELSE v_product.image_url END);
 END LOOP;
 SELECT total,subtotal INTO v_total,v_subtotal FROM public.orders WHERE id=v_order_id;
 RETURN jsonb_build_object('success',true,'duplicate',false,'orderId',v_order_number,'subtotal',v_subtotal,'deliveryCharge',v_delivery,'deliveryZone',v_zone,'paymentMethod','cash_on_delivery','total',v_total,'orderTotal',v_total);
END; $$;
REVOKE ALL ON FUNCTION public.create_website_order(jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.create_website_order(jsonb) TO service_role;

CREATE OR REPLACE FUNCTION public.release_cancelled_order_stock()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE r record; v_before numeric; v_after numeric;
BEGIN
 IF NEW.status='cancelled' AND OLD.status IS DISTINCT FROM 'cancelled' THEN
  PERFORM set_config('app.inventory_system_update','on',true);
  FOR r IN SELECT product_id,sum(-quantity_delta) AS qty FROM public.inventory_movements
    WHERE order_id=NEW.id AND movement_type='order_reserve' AND quantity_delta<0 GROUP BY product_id LOOP
   SELECT stock_quantity INTO v_before FROM public.products WHERE id=r.product_id FOR UPDATE;
   IF v_before IS NOT NULL AND r.qty>0 THEN
    v_after:=v_before+r.qty;
    UPDATE public.products SET stock_quantity=v_after,updated_at=now() WHERE id=r.product_id;
    INSERT INTO public.inventory_movements(product_id,movement_type,quantity_delta,stock_before,stock_after,order_id,reason,created_by)
    VALUES(r.product_id,'order_cancel_release',r.qty,v_before,v_after,NEW.id,'Stock released after order cancellation','order-status-trigger');
   END IF;
  END LOOP;
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_release_cancelled_order_stock ON public.orders;
CREATE TRIGGER trg_release_cancelled_order_stock AFTER UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.release_cancelled_order_stock();
